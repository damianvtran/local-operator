"""The Library's remote feeder: peer sessions' files enter the SAME index tables.

docs/design/remote-files-parity.md §5. METADATA ONLY: for each reachable remote
session the owner's Files index is listed (``peer_session_files``, pages of
:data:`PAGE_LIMIT`) when its catalogue ``mtime`` moved, and its rows become
occurrence rows exactly as a local scan's do — so the grid, facets, search and
dedup need no second path. No byte moves here; thumbnails are generated by the
existing thread only once bytes are local (precache or an open).

Identity:
- a digest row keeps ``a:<digest>``: the same bytes on two devices are ONE asset;
- a path row gets ``r:<device>:<session>:<display path>`` with ``path`` NULL, so a
  remote asset can never resolve to a file on THIS disk (I5-1).

Lifecycle: a session absent from :data:`MISSES_TO_DROP` consecutive successful
catalogue reads (moved, deleted) is dropped; an UNREACHABLE peer's rows are kept;
a session that became local is left to the local scanner. Runs on the indexer's
worker thread (blocking calls are fine there); one owner request in flight.
"""

from __future__ import annotations

import logging
import time
from pathlib import Path
from typing import Any, Callable

from local_operator.library import identity

logger = logging.getLogger(__name__)

#: The Files index's own page ceiling (``session_files.service.MAX_LIMIT``).
PAGE_LIMIT = 200
#: Pages per session per pass: 200 x 50 = 10,000 rows, beyond any measured family.
MAX_PAGES = 50
#: Consecutive successful catalogue reads a session must be absent from to drop.
MISSES_TO_DROP = 2


def _ask(config_dir: Path, peer: str, session_id: str, query: dict[str, Any]) -> dict[str, Any]:
    from local_operator.network.file_index import INDEX_CLIENT_TIMEOUT_S
    from local_operator.server.utils import desktop_mesh

    return desktop_mesh._call(  # noqa: SLF001 — the desktop's one relay seam
        config_dir,
        "peer_session_files",
        timeout=INDEX_CLIENT_TIMEOUT_S,
        peer=peer,
        session_id=session_id,
        phase="list",
        index="files",
        query=query,
    )


def occurrence_rows(
    session_id: str, title: str, device_id: str, device_name: str, rows: list[dict[str, Any]]
) -> list[dict[str, Any]]:
    """The owner's projected rows as index occurrence rows (the local scan's shape)."""
    out: list[dict[str, Any]] = []
    for row in rows:
        ref = row.get("ref") or {}
        session = row.get("session") or {}
        digest = ref.get("digest") if ref.get("type") == "artifact" else None
        display = ref.get("path") if ref.get("type") == "path" else None
        try:
            key = (
                identity.digest_key(str(digest))
                if digest
                else identity.remote_key(device_id, session_id, str(display or ""))
            )
        except ValueError:
            continue
        out.append(
            {
                "asset_id": identity.asset_id(key),
                "key": key,
                "session_id": session_id,
                "title": title,
                "child_id": str(session.get("child_id") or ""),
                "label": session.get("label"),
                "origin": str(row.get("origin") or "mentioned"),
                "tool": str(row.get("tool") or ""),
                "intent": row.get("intent"),
                "first_ts": float(row.get("first_ts") or 0.0),
                "last_ts": float(row.get("last_ts") or 0.0),
                "first_seq": int(row.get("first_seq") or 0),
                "last_seq": int(row.get("last_seq") or 0),
                "touches": int(row.get("touches") or 1),
                "highlighted": 1 if row.get("highlighted") else 0,
                "name": str(row.get("name") or ""),
                # NULL BY CONSTRUCTION (I5-1): the owner's path names THAT disk.
                "path": None,
                "kind": str(row.get("kind") or "other"),
                "content_type": ref.get("content_type"),
                "size_bytes": row.get("size_bytes"),
                "width": row.get("width"),
                "height": row.get("height"),
                "duration_s": row.get("duration_s"),
                "origin_device": device_id,
                "origin_device_name": device_name,
                "remote_file_id": str(row.get("id") or ""),
            }
        )
    return out


def list_all(
    ask: Callable[[dict[str, Any]], dict[str, Any]],
) -> tuple[list[dict[str, Any]], int, bool]:
    """Every row of one owner index, paged: ``(rows, revision, complete)``."""
    rows: list[dict[str, Any]] = []
    cursor: str | None = None
    revision = 0
    for _page in range(MAX_PAGES):
        query: dict[str, Any] = {"scope": "family", "sort": "recent", "limit": PAGE_LIMIT}
        if cursor:
            query["cursor"] = cursor
        answer = ask(query)
        if answer.get("cursor_reset"):
            # The owner's index moved under the walk: restart once from the top.
            rows, cursor = [], None
            continue
        revision = int(answer.get("revision") or 0)
        rows.extend(answer.get("rows") or [])
        cursor = answer.get("next_cursor")
        if answer.get("state") != "ready":
            return rows, revision, False
        if not cursor:
            return rows, revision, True
    return rows, revision, False


def feed(indexer: Any, *, catalogue: list[dict[str, Any]] | None = None) -> int:
    """One pass over the remote catalogue. Returns how many sessions were (re)indexed."""
    from local_operator.library.metadata import MetadataStore
    from local_operator.network.types import MeshRefusal
    from local_operator.server.utils import desktop_mesh

    config_dir = Path(indexer.config_dir)
    store = indexer.store
    if catalogue is None:
        if not desktop_mesh.has_any_network(config_dir):
            return 0
        try:
            catalogue = desktop_mesh.remote_session_rows(config_dir, pins=set())
        except Exception:  # noqa: BLE001 — an unreadable catalogue is not an absence
            logger.debug("library: remote catalogue unavailable", exc_info=True)
            return 0
    known = {sid: row for sid, row in store.sessions().items() if row.get("origin_device")}
    present = {str(row.get("id") or "") for row in catalogue}
    # Only a device that ANSWERED can say a session is gone; a silent one keeps its rows.
    answered = {str(row.get("owner_device") or "") for row in catalogue}
    _age_out(indexer, {s: r for s, r in known.items() if r["origin_device"] in answered}, present)
    indexed = 0
    for row in sorted(catalogue, key=lambda r: float(r.get("mtime") or 0.0), reverse=True):
        session_id = str(row.get("id") or "")
        device_id = str(row.get("owner_device") or "")
        if not session_id or not device_id or not row.get("reachable", True):
            continue  # an unreachable peer's rows are KEPT, not refreshed
        if (config_dir / "sessions" / session_id).is_dir():
            if session_id in known:
                indexer._forget(session_id)  # noqa: SLF001 — the local scanner owns it now
            continue
        mtime = float(row.get("mtime") or 0.0)
        previous = known.get(session_id)
        if previous and previous.get("complete") and float(previous.get("sig_mtime")) == mtime:
            continue
        device_name = str(row.get("owner_device_name") or "")
        title = str(row.get("name") or "") or session_id
        try:
            owner_rows, revision, complete = list_all(
                lambda query: _ask(config_dir, device_id, session_id, query)
            )
        except MeshRefusal as refusal:
            with store.write() as connection:
                store.record_session(
                    connection,
                    session_id,
                    title=title,
                    sig={"mtime": -1},
                    complete=False,
                    error=refusal.code,
                    origin_device=device_id,
                )
            continue
        rows = occurrence_rows(session_id, title, device_id, device_name, owner_rows)
        assets = {r["asset_id"]: (r["key"], r["name"]) for r in rows}
        MetadataStore(config_dir).ensure_assets(
            (asset_id, key, name or None) for asset_id, (key, name) in assets.items()
        )
        with store.write() as connection:
            affected = store.replace_session_occurrences(connection, session_id, rows)
            store.recompute_assets(connection, affected)
            store.record_session(
                connection,
                session_id,
                title=title,
                sig={"mtime": mtime if complete else -1},
                complete=complete,
                revision=float(revision),
                origin_device=device_id,
            )
            if affected:
                store.bump_revision(connection)
        indexer._enqueue_thumbs(assets)  # noqa: SLF001 — generated only if bytes are local
        indexed += 1
    if indexed:
        logger.info("library: indexed %d remote session(s) at %.0f", indexed, time.time())
    return indexed


def _age_out(indexer: Any, known: dict[str, dict[str, Any]], present: set[str]) -> None:
    """Drop a remote session missing from MISSES_TO_DROP successful reads in a row."""
    store = indexer.store
    for session_id, row in known.items():
        if session_id in present:
            continue
        misses = int(row.get("misses") or 0) + 1
        if misses >= MISSES_TO_DROP:
            indexer._forget(session_id)  # noqa: SLF001
            continue
        with store.write() as connection:
            connection.execute(
                "UPDATE idx_sessions SET misses = ? WHERE session_id = ?", (misses, session_id)
            )
