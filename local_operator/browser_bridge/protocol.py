"""Versioned messages shared by the browser bridge and Chromium extension.

This module is the protocol's only hand-written source.  The checked-in
TypeScript representation is generated by :mod:`.gen_ts`; keeping the wire
shape here makes a Python-only protocol edit fail CI instead of drifting until
an extension command mysteriously times out.
"""

from __future__ import annotations

from enum import StrEnum
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field

PROTO_VERSION = 1

#: Every RPC method the extension answers, in a stable order. This is the ONE
#: source of truth: the daemon's timeout table, the tool's action list, and the
#: generated TypeScript ``Method`` union all derive from it, so a method added
#: here without a handler fails a test rather than timing out on the wire, and a
#: method the extension can serve but nobody advertises simply does not exist.
#: ``scroll`` and ``logs`` are bridge-only capabilities (cmux degrades with a
#: typed error); they still live here because the wire protocol is shared.
METHODS = (
    "open",
    "goto",
    "read",
    "snapshot",
    "screenshot",
    "click",
    "type",
    "close",
    "status",
    "scroll",
    "logs",
)


#: How long the extension's approval popup gives the user to answer an origin
#: prompt before auto-denying with a typed ORIGIN_DENIED (origins.ts consumes
#: the generated copy in protocol.gen.ts). Milliseconds because it feeds a
#: chrome ``setTimeout`` directly.
#:
#: Timeout-chain invariant (finding A3): extension deny (60 s) < daemon prompt
#: window (65 s) < session client timeout (base command timeout + prompt window
#: + margin, backend.py). Each layer must outlive the one below it so the
#: innermost deadline always wins the race and the session receives a TYPED
#: answer (origin_denied / nav_timeout / result) instead of a transport
#: timeout. When the session client fired first (it used a flat 30–35 s), a
#: healthy daemon waiting on a human was misreported as "bridge unreachable"
#: and a QA session (transcript 0ee4974ba84a) burned an hour restarting a
#: daemon that was fine. All three constants live in or derive from this
#: module so the relationship cannot drift.
ORIGIN_PROMPT_TIMEOUT_MS = 60_000

#: Per-method base budgets for a command the extension is actively serving.
#: The daemon enforces these; the session client derives its own longer
#: HTTP timeout from them (backend.py) so the daemon's typed timeout always
#: arrives before the client gives up.
COMMAND_TIMEOUTS = {
    "open": 30.0,
    "goto": 30.0,
    "click": 25.0,
    "type": 25.0,
    "read": 20.0,
    "snapshot": 20.0,
    "screenshot": 20.0,
    "close": 20.0,
    "status": 20.0,
    # scroll waits briefly for the wheel/scrollIntoView to settle and re-reads
    # position; logs just drains a per-tab ring buffer already in memory.
    "scroll": 20.0,
    "logs": 20.0,
}

#: Extra budget granted to a command that is BLOCKED on a human origin
#: decision, on top of the base command timeout. The extension gives the user
#: 60 s to answer (ORIGIN_PROMPT_TIMEOUT_MS above); without this the 25–30 s
#: command timeout fired first, so a user who took longer than that got a
#: spurious tool failure while the tab navigated anyway against a surface the
#: session had written off (finding A3). Derived slightly above the extension's
#: deny-timeout so that deny wins the race and returns a typed ORIGIN_DENIED
#: rather than this firing blind.
ORIGIN_PROMPT_WINDOW_S = ORIGIN_PROMPT_TIMEOUT_MS / 1000 + 5.0


class ErrorCode(StrEnum):
    EXTENSION_DISCONNECTED = "extension_disconnected"
    NOT_PAIRED = "not_paired"
    TAB_CLOSED = "tab_closed"
    NAV_FAILED = "nav_failed"
    NAV_TIMEOUT = "nav_timeout"
    ELEMENT_NOT_FOUND = "element_not_found"
    ORIGIN_DENIED = "origin_denied"
    ORIGIN_PROMPT_PENDING = "origin_prompt_pending"
    DEBUGGER_CONFLICT = "debugger_conflict"
    BUSY = "busy"
    PROTO_MISMATCH = "proto_mismatch"
    INTERNAL = "internal"


class WireModel(BaseModel):
    """Strict envelopes make version skew fail at the boundary, not later."""

    model_config = ConfigDict(extra="forbid")


class Request(WireModel):
    id: str = Field(min_length=1)
    method: str = Field(min_length=1)
    params: dict[str, Any] = Field(default_factory=dict)


class ErrorDetail(WireModel):
    code: ErrorCode
    message: str
    data: dict[str, Any] = Field(default_factory=dict)


class Response(WireModel):
    id: str
    ok: bool
    result: dict[str, Any] | None = None
    error: ErrorDetail | None = None


class Hello(WireModel):
    event: Literal["hello"] = "hello"
    proto: int
    token: str = ""
    extension_version: str
    browser: str


class HelloAck(WireModel):
    event: Literal["hello_ack"] = "hello_ack"
    proto: int = PROTO_VERSION
    paired: bool


class PairRequest(WireModel):
    event: Literal["pair"] = "pair"
    code: str = Field(pattern=r"^[0-9]{6}$")


class PairResult(WireModel):
    event: Literal["pair_result"] = "pair_result"
    ok: bool
    token: str = ""
    message: str = ""


class Ping(WireModel):
    event: Literal["ping"] = "ping"


class Pong(WireModel):
    event: Literal["pong"] = "pong"


class TabClosed(WireModel):
    event: Literal["tab_closed"] = "tab_closed"
    tab: str


class TabUpdate(WireModel):
    """Extension -> daemon: the driven tab navigated. Lets the daemon report the
    current page to the Connected popup without an extra RPC (finding U3)."""

    event: Literal["tab_update"] = "tab_update"
    url: str = ""
    title: str = ""


class AwaitingOrigin(WireModel):
    """Extension -> daemon: a command is blocked on a human origin decision, so
    the daemon extends that command's deadline past the base timeout (A3) and
    can surface the pending site (U2)."""

    event: Literal["awaiting_origin"] = "awaiting_origin"
    id: str
    origin: str = ""


class Unpair(WireModel):
    """Extension -> daemon: the options page revoked pairing, so the daemon must
    drop the live socket, not merely the next reconnect (findings A5/U1)."""

    event: Literal["unpair"] = "unpair"


class OriginDecision(WireModel):
    event: Literal["origin_decision"] = "origin_decision"
    origin: str
    decision: Literal["once", "always", "deny"]
