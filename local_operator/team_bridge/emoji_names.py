"""Resolve a reaction emoji to the ONE canonical form the hub stores.

WHY. The hub keys a reaction by one fully-qualified RGI emoji sequence
(agent-server ``internal/bridge/emoji.Normalize``: NFC, <=128 UTF-8 bytes,
allowlisted) and refuses anything else with ``rule=not_an_emoji``. Agents
naturally write Slack/GitHub shortcodes (``white_check_mark``, ``:+1:``), and
a literal typed without its variation selector (``❤`` instead of ``❤️``) is a
different key from what a picker emits, so the two would not stack. Both the
agent tool (``bridge op=react``) and the desktop/relay route call
:func:`normalize_reaction_emoji` so every client sends the same key.

CONSTRAINTS.

* The table (``emoji_names.json``) is GENERATED by
  ``scripts/gen_emoji_names.py`` from pinned gemoji + Unicode emoji-test 18.0
  (the version agent-server pins); never edit it by hand.
* The hub stays the authority on "is this RGI". A literal that is not a
  shortcode is passed through (NFC, plus the FE0F qualification when the table
  knows the qualified form), so an emoji newer than this table still works the
  day the hub learns it. Only shortcode input is resolved locally, and an
  unknown one is refused
  here with a clear message instead of a raw server refusal. Pure-ASCII
  input is always treated as a shortcode, because no RGI emoji is ASCII.
* Matching (identical to agent-server ``emoji.foldShortcode``): trim ASCII
  whitespace, then surrounding colons, then whitespace again; fold case; and
  collapse each run of ``-`` / ASCII whitespace / ``_`` to one ``_``
  (``thumbs-up`` == ``Thumbs  up`` == ``: thumbs_up :``). The generator refuses
  a table in which that fold makes two emoji share a key.
* The name table is the SAME one the hub resolves (skin-tone CLDR names such as
  ``thumbs_up_medium_skin_tone`` included), pinned by one shared digest in both
  repos, so a shortcode the hub accepts from the UI is never refused here.
  Slack skin-tone suffixes (``:+1::skin-tone-3:``) are deliberately not
  parsed; a literal skin-toned emoji or the CLDR name works.
"""

from __future__ import annotations

import json
import re
import unicodedata
from functools import lru_cache
from importlib import resources
from typing import Any

#: The hub's reaction-key byte bound (agent-server §10.2).
REACTION_EMOJI_MAX_BYTES = 128

#: Wording shared by both callers so an agent and the desktop see one message.
ACCEPTED_FORMS_HINT = (
    "use a Unicode emoji (✅) or a shortcode such as ':white_check_mark:' or "
    "'white_check_mark' (also +1, eyes, tada, rocket, heart)"
)


#: ASCII whitespace exactly as the hub's fold trims it. ``str.strip()`` with no
#: argument also strips U+001C..U+001F, which Go does not, so the set is explicit.
_WS = " \t\n\v\f\r"
_SEPARATORS = re.compile(r"[-_ \t\n\v\f\r]+")


def shortcode_key(raw: str) -> str:
    """Fold a shortcode to the table's key grammar (see module docstring)."""

    return _SEPARATORS.sub("_", raw.strip(_WS).strip(":").strip(_WS).lower())


@lru_cache(maxsize=1)
def _table() -> dict[str, Any]:
    # Loaded lazily: the react path is rare and the table is ~125 KB.
    raw = resources.files(__package__).joinpath("emoji_names.json").read_text(encoding="utf-8")
    return json.loads(raw)


def emoji_names() -> dict[str, str]:
    """The shortcode -> fully-qualified emoji table."""

    return _table()["names"]


def normalize_reaction_emoji(raw: str) -> str | None:
    """Return the canonical reaction key for ``raw``, or ``None`` if unusable.

    ``None`` means: empty, over the hub's byte bound, or shortcode-shaped but
    unknown (any pure-ASCII miss). A non-ASCII literal is returned NFC-normalised and qualified;
    whether it is one RGI emoji remains the hub's decision.
    """

    text = unicodedata.normalize("NFC", raw or "").strip()
    if not text:
        return None
    if text.isascii():
        # No RGI emoji is pure ASCII (even a keycap needs U+FE0F U+20E3), so
        # ASCII input can only be a shortcode; a miss is refused here rather
        # than spending a hub round trip on a guaranteed ``not_an_emoji``.
        key = shortcode_key(text)
        return emoji_names().get(key) if key else None
    # ``:✅:`` is a literal wrapped in shortcode colons; unwrap it so it resolves
    # here instead of reaching the hub, which would refuse the colons.
    text = text.strip(":").strip() or text
    key = _table()["qualify"].get(text, text)
    if len(key.encode("utf-8")) > REACTION_EMOJI_MAX_BYTES:
        return None
    return key
